-- =============================================================================
-- File: script/01_schema.sql
-- Project: Chat System (Version 1 — Shared PostgreSQL Database Schema)
-- Target Engine: PostgreSQL 15+ (UTF-8)
--
-- IMPORTANT EXECUTION NOTES:
-- 1. This initial DDL script is intended for an ALREADY-CREATED, EMPTY
--    PostgreSQL database.
-- 2. It does NOT include DROP DATABASE, DROP SCHEMA CASCADE, TRUNCATE, or
--    CREATE TABLE IF NOT EXISTS, so incompatible pre-existing tables will
--    fail fast rather than being silently ignored or destructively wiped.
-- 3. No optional PostgreSQL extensions are required.
-- 4. All foreign keys on historical/audit tables use ON DELETE RESTRICT so
--    account or group records are never silently cascaded through login,
--    app-open, friendship, message, or spam-report history. Account deletion
--    is modeled as soft deletion via users.deleted_at.
-- 5. users.updated_at is application-maintained: DEFAULT now() initializes it
--    on INSERT, and the service layer must set updated_at = now() on UPDATE.
-- =============================================================================

BEGIN;

SET client_encoding = 'UTF8';

-- -----------------------------------------------------------------------------
-- 1. Table: users
-- Stores both regular user accounts ('USER') and administrator accounts ('ADMIN').
-- Note:
--   - Online/offline status is managed by live socket sessions in Version 2
--     and is intentionally not persisted in this table.
--   - Password reset/update replaces password_hash; no plaintext password
--     column exists.
--   - updated_at is application-maintained on subsequent edits (DEFAULT now()
--     applies only on row insertion).
-- -----------------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username        TEXT        NOT NULL,
    password_hash   TEXT        NOT NULL,
    full_name       TEXT        NOT NULL,
    address         TEXT        NULL,
    date_of_birth   DATE        NULL,
    gender          TEXT        NOT NULL DEFAULT 'OTHER',
    email           TEXT        NOT NULL,
    role            TEXT        NOT NULL DEFAULT 'USER',
    is_locked       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ NULL,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT chk_users_username_nonempty CHECK (COALESCE(btrim(username), '') <> ''),
    CONSTRAINT chk_users_password_hash_nonempty CHECK (COALESCE(btrim(password_hash), '') <> ''),
    CONSTRAINT chk_users_full_name_nonempty CHECK (COALESCE(btrim(full_name), '') <> ''),
    CONSTRAINT chk_users_email_nonempty CHECK (COALESCE(btrim(email), '') <> ''),
    CONSTRAINT chk_users_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT chk_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT chk_users_updated_at_order CHECK (updated_at >= created_at),
    CONSTRAINT chk_users_deleted_at_order CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);

-- Case-insensitive uniqueness on username and email without optional extensions
CREATE UNIQUE INDEX uq_users_username_lower ON users (LOWER(username));
CREATE UNIQUE INDEX uq_users_email_lower ON users (LOWER(email));

-- Indexes for Admin & User filtering and sorting
CREATE INDEX idx_users_created_at ON users (created_at);
CREATE INDEX idx_users_full_name ON users (full_name);
CREATE INDEX idx_users_active_not_deleted ON users (id) WHERE deleted_at IS NULL;


-- -----------------------------------------------------------------------------
-- 2. Table: login_history
-- Records successful authentication sessions for per-user and system-wide logs.
-- -----------------------------------------------------------------------------
CREATE TABLE login_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT      NOT NULL,
    login_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    logout_at   TIMESTAMPTZ NULL,
    ip_address  TEXT        NULL,

    CONSTRAINT pk_login_history PRIMARY KEY (id),
    CONSTRAINT fk_login_history_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_login_history_logout_order CHECK (
        logout_at IS NULL OR logout_at >= login_at
    ),
    CONSTRAINT chk_login_history_ip_nonempty CHECK (
        ip_address IS NULL OR COALESCE(btrim(ip_address), '') <> ''
    )
);

CREATE INDEX idx_login_history_login_at_desc ON login_history (login_at DESC);
CREATE INDEX idx_login_history_user_login_desc ON login_history (user_id, login_at DESC);


-- -----------------------------------------------------------------------------
-- 3. Table: app_open_events
-- Tracks authenticated application process launches separately from logins.
-- Each User-app JVM launch generates one launch_id UUID; at most one row is
-- recorded per (launch_id, user_id).
-- -----------------------------------------------------------------------------
CREATE TABLE app_open_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    launch_id   UUID        NOT NULL,
    user_id     BIGINT      NOT NULL,
    opened_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_app_open_events PRIMARY KEY (id),
    CONSTRAINT fk_app_open_events_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uq_app_open_events_launch_user UNIQUE (launch_id, user_id)
);

CREATE INDEX idx_app_open_events_opened_at_user ON app_open_events (opened_at, user_id);
CREATE INDEX idx_app_open_events_user_opened_at ON app_open_events (user_id, opened_at);


-- -----------------------------------------------------------------------------
-- 4. Table: friend_requests
-- Tracks friend request lifecycle states. At most one PENDING request may exist
-- per unordered user pair at any time.
-- -----------------------------------------------------------------------------
CREATE TABLE friend_requests (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sender_id       BIGINT      NOT NULL,
    receiver_id     BIGINT      NOT NULL,
    status          TEXT        NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    responded_at    TIMESTAMPTZ NULL,

    CONSTRAINT pk_friend_requests PRIMARY KEY (id),
    CONSTRAINT fk_friend_requests_sender FOREIGN KEY (sender_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_friend_requests_receiver FOREIGN KEY (receiver_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_friend_requests_no_self CHECK (sender_id <> receiver_id),
    CONSTRAINT chk_friend_requests_status CHECK (
        status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')
    ),
    CONSTRAINT chk_friend_requests_response_consistency CHECK (
        (status = 'PENDING' AND responded_at IS NULL)
        OR
        (
            status IN ('ACCEPTED', 'REJECTED', 'CANCELLED')
            AND responded_at IS NOT NULL
            AND responded_at >= created_at
        )
    )
);

-- At most one PENDING request per unordered pair (min(u,v), max(u,v))
CREATE UNIQUE INDEX uq_friend_requests_pending_pair
    ON friend_requests (LEAST(sender_id, receiver_id), GREATEST(sender_id, receiver_id))
    WHERE status = 'PENDING';

CREATE INDEX idx_friend_requests_receiver_status
    ON friend_requests (receiver_id, status, created_at DESC);
CREATE INDEX idx_friend_requests_sender_status
    ON friend_requests (sender_id, status, created_at DESC);


-- -----------------------------------------------------------------------------
-- 5. Table: friendships
-- Stores accepted friendships only, using a single canonical row per pair
-- with user_low_id < user_high_id.
-- -----------------------------------------------------------------------------
CREATE TABLE friendships (
    user_low_id     BIGINT      NOT NULL,
    user_high_id    BIGINT      NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_friendships PRIMARY KEY (user_low_id, user_high_id),
    CONSTRAINT fk_friendships_user_low FOREIGN KEY (user_low_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_friendships_user_high FOREIGN KEY (user_high_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_friendships_canonical_order CHECK (user_low_id < user_high_id)
);

-- Reverse index for fast bidirectional 1-hop and 2-hop graph traversal
CREATE INDEX idx_friendships_high_low ON friendships (user_high_id, user_low_id);


-- -----------------------------------------------------------------------------
-- 6. Table: user_blocks
-- Stores directional user blocks.
-- -----------------------------------------------------------------------------
CREATE TABLE user_blocks (
    blocker_id  BIGINT      NOT NULL,
    blocked_id  BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_user_blocks PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT fk_user_blocks_blocker FOREIGN KEY (blocker_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_blocks_blocked FOREIGN KEY (blocked_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_user_blocks_no_self CHECK (blocker_id <> blocked_id)
);

CREATE INDEX idx_user_blocks_blocked_blocker ON user_blocks (blocked_id, blocker_id);


-- -----------------------------------------------------------------------------
-- 7. Table: direct_messages
-- Stores 1-to-1 chat messages.
-- -----------------------------------------------------------------------------
CREATE TABLE direct_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sender_id   BIGINT      NOT NULL,
    receiver_id BIGINT      NOT NULL,
    content     TEXT        NOT NULL,
    sent_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_direct_messages PRIMARY KEY (id),
    CONSTRAINT fk_direct_messages_sender FOREIGN KEY (sender_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_direct_messages_receiver FOREIGN KEY (receiver_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_direct_messages_no_self CHECK (sender_id <> receiver_id),
    CONSTRAINT chk_direct_messages_content_nonempty CHECK (COALESCE(btrim(content), '') <> '')
);

CREATE INDEX idx_direct_messages_conversation_time
    ON direct_messages (LEAST(sender_id, receiver_id), GREATEST(sender_id, receiver_id), sent_at DESC);
CREATE INDEX idx_direct_messages_sender_sent_at
    ON direct_messages (sender_id, sent_at, receiver_id);
CREATE INDEX idx_direct_messages_receiver_sent_at
    ON direct_messages (receiver_id, sent_at, sender_id);


-- -----------------------------------------------------------------------------
-- 8. Table: direct_message_hidden
-- Tracks per-user hiding of direct messages without deleting underlying rows.
-- -----------------------------------------------------------------------------
CREATE TABLE direct_message_hidden (
    message_id  BIGINT      NOT NULL,
    user_id     BIGINT      NOT NULL,
    hidden_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_direct_message_hidden PRIMARY KEY (message_id, user_id),
    CONSTRAINT fk_direct_message_hidden_message FOREIGN KEY (message_id)
        REFERENCES direct_messages (id) ON DELETE RESTRICT,
    CONSTRAINT fk_direct_message_hidden_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_direct_message_hidden_user_msg
    ON direct_message_hidden (user_id, message_id);


-- -----------------------------------------------------------------------------
-- 9. Table: chat_groups
-- Stores multi-user chat groups and encryption mode indicator.
-- -----------------------------------------------------------------------------
CREATE TABLE chat_groups (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            TEXT        NOT NULL,
    created_by      BIGINT      NOT NULL,
    is_encrypted    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_chat_groups PRIMARY KEY (id),
    CONSTRAINT fk_chat_groups_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_chat_groups_name_nonempty CHECK (COALESCE(btrim(name), '') <> '')
);

CREATE INDEX idx_chat_groups_name ON chat_groups (name);
CREATE INDEX idx_chat_groups_created_at ON chat_groups (created_at DESC);
CREATE INDEX idx_chat_groups_created_by ON chat_groups (created_by);


-- -----------------------------------------------------------------------------
-- 10. Table: group_members
-- Represents current/latest membership state for each (group_id, user_id) pair.
-- Note: Does not store a multi-interval join/leave history timeline.
-- -----------------------------------------------------------------------------
CREATE TABLE group_members (
    group_id    BIGINT      NOT NULL,
    user_id     BIGINT      NOT NULL,
    role        TEXT        NOT NULL DEFAULT 'MEMBER',
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at     TIMESTAMPTZ NULL,

    CONSTRAINT pk_group_members PRIMARY KEY (group_id, user_id),
    CONSTRAINT fk_group_members_group FOREIGN KEY (group_id)
        REFERENCES chat_groups (id) ON DELETE RESTRICT,
    CONSTRAINT fk_group_members_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_group_members_role CHECK (role IN ('MEMBER', 'ADMIN')),
    CONSTRAINT chk_group_members_left_order CHECK (left_at IS NULL OR left_at >= joined_at)
);

CREATE INDEX idx_group_members_active_group_role
    ON group_members (group_id, role) WHERE left_at IS NULL;
CREATE INDEX idx_group_members_active_user
    ON group_members (user_id, group_id) WHERE left_at IS NULL;


-- -----------------------------------------------------------------------------
-- 11. Table: user_public_keys
-- Encryption storage preparation: stores user public keys for wrapping group keys.
-- Private keys are never stored in the database.
-- -----------------------------------------------------------------------------
CREATE TABLE user_public_keys (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT      NOT NULL,
    public_key  TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at  TIMESTAMPTZ NULL,

    CONSTRAINT pk_user_public_keys PRIMARY KEY (id),
    CONSTRAINT fk_user_public_keys_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_user_public_keys_nonempty CHECK (COALESCE(btrim(public_key), '') <> ''),
    CONSTRAINT chk_user_public_keys_revoked_order CHECK (
        revoked_at IS NULL OR revoked_at >= created_at
    )
);

CREATE INDEX idx_user_public_keys_active_user
    ON user_public_keys (user_id, created_at DESC) WHERE revoked_at IS NULL;


-- -----------------------------------------------------------------------------
-- 12. Table: group_key_versions
-- Encryption storage preparation: tracks symmetric key versions per group.
-- Plaintext group keys are never stored in the database.
-- -----------------------------------------------------------------------------
CREATE TABLE group_key_versions (
    group_id    BIGINT      NOT NULL,
    key_version INTEGER     NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_group_key_versions PRIMARY KEY (group_id, key_version),
    CONSTRAINT fk_group_key_versions_group FOREIGN KEY (group_id)
        REFERENCES chat_groups (id) ON DELETE RESTRICT,
    CONSTRAINT chk_group_key_versions_positive CHECK (key_version >= 1)
);


-- -----------------------------------------------------------------------------
-- 13. Table: group_key_envelopes
-- Encryption storage preparation: stores wrapped group keys per member public key.
-- -----------------------------------------------------------------------------
CREATE TABLE group_key_envelopes (
    group_id            BIGINT  NOT NULL,
    key_version         INTEGER NOT NULL,
    user_public_key_id  BIGINT  NOT NULL,
    encrypted_group_key BYTEA   NOT NULL,

    CONSTRAINT pk_group_key_envelopes PRIMARY KEY (group_id, key_version, user_public_key_id),
    CONSTRAINT fk_group_key_envelopes_version FOREIGN KEY (group_id, key_version)
        REFERENCES group_key_versions (group_id, key_version) ON DELETE RESTRICT,
    CONSTRAINT fk_group_key_envelopes_pubkey FOREIGN KEY (user_public_key_id)
        REFERENCES user_public_keys (id) ON DELETE RESTRICT,
    CONSTRAINT chk_group_key_envelopes_nonempty CHECK (
        COALESCE(octet_length(encrypted_group_key), 0) > 0
    )
);

CREATE INDEX idx_group_key_envelopes_pubkey
    ON group_key_envelopes (user_public_key_id, group_id, key_version);


-- -----------------------------------------------------------------------------
-- 14. Table: group_messages
-- Stores group messages in either plaintext mode OR encrypted mode:
--   - Plaintext mode: content IS NOT NULL (non-blank) AND ciphertext, nonce,
--     and key_version are all NULL.
--   - Encrypted mode: content IS NULL AND ciphertext (non-empty), nonce
--     (non-empty), and key_version are all NOT NULL, referencing
--     group_key_versions(group_id, key_version) of the SAME group.
-- -----------------------------------------------------------------------------
CREATE TABLE group_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_id    BIGINT      NOT NULL,
    sender_id   BIGINT      NOT NULL,
    content     TEXT        NULL,
    ciphertext  BYTEA       NULL,
    nonce       BYTEA       NULL,
    key_version INTEGER     NULL,
    sent_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_group_messages PRIMARY KEY (id),
    CONSTRAINT fk_group_messages_group FOREIGN KEY (group_id)
        REFERENCES chat_groups (id) ON DELETE RESTRICT,
    CONSTRAINT fk_group_messages_sender FOREIGN KEY (sender_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_group_messages_key_version FOREIGN KEY (group_id, key_version)
        REFERENCES group_key_versions (group_id, key_version) ON DELETE RESTRICT,
    CONSTRAINT chk_group_messages_payload_mode CHECK (
        (
            content IS NOT NULL
            AND COALESCE(btrim(content), '') <> ''
            AND ciphertext IS NULL
            AND nonce IS NULL
            AND key_version IS NULL
        )
        OR
        (
            content IS NULL
            AND ciphertext IS NOT NULL
            AND COALESCE(octet_length(ciphertext), 0) > 0
            AND nonce IS NOT NULL
            AND COALESCE(octet_length(nonce), 0) > 0
            AND key_version IS NOT NULL
        )
    )
);

CREATE INDEX idx_group_messages_group_sent_at
    ON group_messages (group_id, sent_at DESC);
CREATE INDEX idx_group_messages_sender_sent_at
    ON group_messages (sender_id, sent_at, group_id);
CREATE INDEX idx_group_messages_group_key_version
    ON group_messages (group_id, key_version) WHERE key_version IS NOT NULL;


-- -----------------------------------------------------------------------------
-- 15. Table: group_message_hidden
-- Tracks per-user hiding of group messages without deleting underlying rows.
-- -----------------------------------------------------------------------------
CREATE TABLE group_message_hidden (
    message_id  BIGINT      NOT NULL,
    user_id     BIGINT      NOT NULL,
    hidden_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_group_message_hidden PRIMARY KEY (message_id, user_id),
    CONSTRAINT fk_group_message_hidden_message FOREIGN KEY (message_id)
        REFERENCES group_messages (id) ON DELETE RESTRICT,
    CONSTRAINT fk_group_message_hidden_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_group_message_hidden_user_msg
    ON group_message_hidden (user_id, message_id);


-- -----------------------------------------------------------------------------
-- 16. Table: spam_reports
-- Stores user-submitted spam reports and administrator resolution metadata.
-- -----------------------------------------------------------------------------
CREATE TABLE spam_reports (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reporter_id         BIGINT      NOT NULL,
    reported_user_id    BIGINT      NOT NULL,
    direct_message_id   BIGINT      NULL,
    reason              TEXT        NOT NULL,
    message_snapshot    TEXT        NULL,
    status              TEXT        NOT NULL DEFAULT 'PENDING',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_by         BIGINT      NULL,
    resolved_at         TIMESTAMPTZ NULL,

    CONSTRAINT pk_spam_reports PRIMARY KEY (id),
    CONSTRAINT fk_spam_reports_reporter FOREIGN KEY (reporter_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_spam_reports_reported_user FOREIGN KEY (reported_user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_spam_reports_direct_message FOREIGN KEY (direct_message_id)
        REFERENCES direct_messages (id) ON DELETE RESTRICT,
    CONSTRAINT fk_spam_reports_resolved_by FOREIGN KEY (resolved_by)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_spam_reports_no_self CHECK (reporter_id <> reported_user_id),
    CONSTRAINT chk_spam_reports_reason_nonempty CHECK (COALESCE(btrim(reason), '') <> ''),
    CONSTRAINT chk_spam_reports_status CHECK (status IN ('PENDING', 'RESOLVED')),
    CONSTRAINT chk_spam_reports_resolution_consistency CHECK (
        (
            status = 'PENDING'
            AND resolved_by IS NULL
            AND resolved_at IS NULL
        )
        OR
        (
            status = 'RESOLVED'
            AND resolved_by IS NOT NULL
            AND resolved_at IS NOT NULL
            AND resolved_at >= created_at
        )
    )
);

CREATE INDEX idx_spam_reports_created_at_desc
    ON spam_reports (created_at DESC);
CREATE INDEX idx_spam_reports_reported_user
    ON spam_reports (reported_user_id, created_at DESC);
CREATE INDEX idx_spam_reports_reporter_user
    ON spam_reports (reporter_id, created_at DESC);

COMMIT;
